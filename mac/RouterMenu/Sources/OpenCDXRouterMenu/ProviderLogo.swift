/// Monochrome provider marks shown before account names. Paths come from the
/// Simple Icons project (CC0) in a 24-point coordinate space; the marks
/// themselves are trademarks of OpenAI and Anthropic, used only to identify
/// each account's provider.
enum AccountProvider: String {
    case openAI = "openai"
    case claude = "claude"
}

struct ProviderLogo: View {
    let provider: AccountProvider
    var size: CGFloat = 11

    var body: some View {
        Group {
            switch provider {
            case .openAI: OpenAILogoShape()
            case .claude: ClaudeLogoShape()
            }
        }
        .frame(width: size, height: size)
        .accessibilityLabel(provider == .claude ? "Claude" : "OpenAI")
    }
}

/// Draws commands authored in a 24 × 24 space into any rectangle.
private struct LogoPath {
    var path = Path()
    let rect: CGRect

    private func point(_ x: CGFloat, _ y: CGFloat) -> CGPoint {
        CGPoint(x: rect.minX + x / 24 * rect.width, y: rect.minY + y / 24 * rect.height)
    }

    mutating func m(_ x: CGFloat, _ y: CGFloat) { path.move(to: point(x, y)) }
    mutating func l(_ x: CGFloat, _ y: CGFloat) { path.addLine(to: point(x, y)) }
    mutating func c(_ x1: CGFloat, _ y1: CGFloat, _ x2: CGFloat, _ y2: CGFloat, _ x: CGFloat, _ y: CGFloat) {
        path.addCurve(to: point(x, y), control1: point(x1, y1), control2: point(x2, y2))
    }
    mutating func q(_ x1: CGFloat, _ y1: CGFloat, _ x: CGFloat, _ y: CGFloat) {
        path.addQuadCurve(to: point(x, y), control: point(x1, y1))
    }
    mutating func z() { path.closeSubpath() }
}

